// Package deviceattest — tpm2_linux.go
//
// TPM 2.0 Linux quote verifier (server-side).
//
// References:
//   - TCG EK Credential Profile v2.5 §3.2 — EK certificate profile
//     https://trustedcomputinggroup.org/wp-content/uploads/TCG_IWG_EKCredentialProfile_v2p5_r2_pub.pdf
//   - TCG TPM 2.0 Part 1 §10 — TPM2_Quote (TPMS_ATTEST structure)
//     https://trustedcomputinggroup.org/wp-content/uploads/TPM-Rev-2.0-Part-1-Architecture-01.07-2014-03-13.pdf
//   - go-attestation AKPublic.Verify — nonce-bound quote verification
//     https://pkg.go.dev/github.com/google/go-attestation/attest#AKPublic.Verify
//   - ADR 0043 §3.c.1 — platform verifier layout
//
// Server-side semantics
// =====================
// jess-controller never opens /dev/tpmrm0. The TPM operations happen on the
// DEVICE (posture-agent in hexxlock-access). The controller receives:
//
//   - AKPublicBlob     — TPMT_PUBLIC serialised bytes of the Attestation Key.
//   - QuoteBlob        — TPMS_ATTEST serialised quote produced by TPM2_Quote.
//   - QuoteSigBlob     — TPMT_SIGNATURE of QuoteBlob, signed by the AK.
//   - NonceClient      — controller-issued freshness nonce embedded in the quote.
//
// VerifyRequest carries these via the PlatformBlob field (JSON-marshalled
// TPM2LinuxQuotePayload). The verifier:
//  1. Parses the AK public key via attest.ParseAKPublic.
//  2. Constructs an attest.Quote from QuoteBlob + QuoteSigBlob.
//  3. Calls AKPublic.Verify(quote, nil, nonce) — verifies the AK signature
//     and nonce binding (PCR slice is nil; we do not attest PCR values here;
//     the quote proves AK liveness, not a specific PCR state).
//  4. Verifies the EK chain via the embedded chainVerifier (Path A).
//
// Platform string: "tpm2-linux"
// Platform specific blob field: VerifyRequest.PlatformBlob

package deviceattest

import (
	"context"
	"crypto/x509"
	"encoding/json"
	"fmt"
	"time"

	"github.com/google/go-attestation/attest"
)

// TPM2LinuxQuotePayload is the JSON structure the posture-agent on Linux
// marshals into VerifyRequest.PlatformBlob. All fields are base64-encoded
// raw bytes to avoid encoding ambiguities in JSON transit.
//
// The controller never interprets the raw bytes except to pass them to the
// go-attestation API — it relies on the library's parsers for structural
// validity checks.
type TPM2LinuxQuotePayload struct {
	// AKPublicBlob is the TPMT_PUBLIC-encoded bytes of the Attestation Key
	// generated by TPM2_CreatePrimary or TPM2_Create on the device. The
	// controller uses this to reconstruct the AK public key for quote
	// signature verification.
	AKPublicBlob []byte `json:"ak_public"`

	// QuoteBlob is the TPMS_ATTEST structure produced by TPM2_Quote, encoded
	// as raw DER/binary per the TCG TPM 2.0 wire format.
	QuoteBlob []byte `json:"quote"`

	// QuoteSigBlob is the TPMT_SIGNATURE structure produced alongside
	// QuoteBlob by TPM2_Quote. The AK signs over the TPMS_ATTEST bytes.
	QuoteSigBlob []byte `json:"quote_sig"`
}

// tpm2LinuxVerifier implements Verifier for Platform="tpm2-linux".
//
// It performs AK quote verification (freshness + signature) then delegates
// EK certificate chain verification to an embedded chainVerifier. The two
// steps together prove:
//   - The quote was produced by a live TPM (via nonce binding).
//   - The TPM is genuine hardware from a trusted vendor (via EK chain).
//
// Trust ceiling: TIER_CORP (same as Path A — TPM2 Linux with EK chain is
// the highest assurance device posture available on Linux).
type tpm2LinuxVerifier struct {
	chain Verifier // wraps chainVerifier for EK certificate validation
	now   func() time.Time
}

// TPM2LinuxOption configures a tpm2LinuxVerifier.
type TPM2LinuxOption func(*tpm2LinuxVerifier)

// WithTPM2LinuxClock replaces the real-time clock. Used in tests.
func WithTPM2LinuxClock(fn func() time.Time) TPM2LinuxOption {
	return func(v *tpm2LinuxVerifier) { v.now = fn }
}

// NewTPM2LinuxVerifier constructs a production TPM 2.0 Linux verifier.
//
// vendorRoots MUST NOT be nil — it is the pinned manufacturer root pool used
// for EK certificate chain verification (TCG EK Credential Profile v2.5
// §3.2.7). Nil vendorRoots panics so the wiring bug surfaces at controller
// startup, not at request time.
//
// Register the returned verifier with:
//
//	registry.Register("tpm2-linux", NewTPM2LinuxVerifier(vendorRoots))
func NewTPM2LinuxVerifier(vendorRoots *x509.CertPool, opts ...TPM2LinuxOption) Verifier {
	if vendorRoots == nil {
		panic("deviceattest: NewTPM2LinuxVerifier: vendorRoots must not be nil")
	}
	v := &tpm2LinuxVerifier{
		chain: NewChainVerifier("tpm2-linux", vendorRoots),
		now:   time.Now,
	}
	for _, o := range opts {
		o(v)
	}
	// Thread the clock option into the embedded chain verifier so that tests
	// can inject a single clock and have both layers honour it.
	if v.now != nil {
		// Rebuild chain verifier with the clock so tests work end-to-end.
		v.chain = NewChainVerifier("tpm2-linux", vendorRoots, WithChainClock(v.now))
	}
	return v
}

// Verify implements Verifier for Platform="tpm2-linux".
//
// Flow:
//  1. Guard: PlatformBlob must be present and parseable as TPM2LinuxQuotePayload.
//  2. Parse the AK public key via attest.ParseAKPublic.
//  3. Verify the AK quote signature + nonce binding via AKPublic.Verify.
//  4. Delegate EK chain verification to the embedded chainVerifier.
//  5. Return TIER_CORP with reasons: "tpm2_linux_quote_verified" +
//     "ek_chain_verified" from the chain verifier.
func (v *tpm2LinuxVerifier) Verify(ctx context.Context, req VerifyRequest) (VerifyResponse, error) {
	// Guard 1: platform blob required.
	if len(req.PlatformBlob) == 0 {
		return VerifyResponse{}, fmt.Errorf(
			"%w: tpm2-linux verifier requires PlatformBlob (TPM2LinuxQuotePayload JSON)",
			ErrVerification,
		)
	}

	// Guard 2: nonce required for replay prevention.
	if len(req.NonceClient) == 0 {
		return VerifyResponse{}, fmt.Errorf(
			"%w: tpm2-linux verifier requires NonceClient for quote freshness binding",
			ErrVerification,
		)
	}

	// Parse the platform-specific payload.
	var payload TPM2LinuxQuotePayload
	if err := json.Unmarshal(req.PlatformBlob, &payload); err != nil {
		return VerifyResponse{}, fmt.Errorf(
			"%w: tpm2-linux PlatformBlob is not valid TPM2LinuxQuotePayload JSON: %v",
			ErrVerification, err,
		)
	}
	if len(payload.AKPublicBlob) == 0 {
		return VerifyResponse{}, fmt.Errorf("%w: tpm2-linux: AKPublicBlob is empty in PlatformBlob", ErrVerification)
	}
	if len(payload.QuoteBlob) == 0 {
		return VerifyResponse{}, fmt.Errorf("%w: tpm2-linux: QuoteBlob is empty in PlatformBlob", ErrVerification)
	}
	if len(payload.QuoteSigBlob) == 0 {
		return VerifyResponse{}, fmt.Errorf("%w: tpm2-linux: QuoteSigBlob is empty in PlatformBlob", ErrVerification)
	}

	// Parse the AK public key. ParseAKPublic decodes the TPMT_PUBLIC bytes
	// and returns the Go crypto.PublicKey + hash algorithm used by the AK.
	akPublic, err := attest.ParseAKPublic(payload.AKPublicBlob)
	if err != nil {
		return VerifyResponse{}, fmt.Errorf(
			"%w: tpm2-linux: AK public key parse failed: %v",
			ErrVerification, err,
		)
	}

	// Construct the attest.Quote from the raw TPM bytes.
	quote := attest.Quote{
		Quote:     payload.QuoteBlob,
		Signature: payload.QuoteSigBlob,
	}

	// Verify the AK quote: checks that QuoteBlob is signed by the AK and
	// that NonceClient appears in the qualifying data (TPMS_ATTEST
	// extraData field). Passing nil PCRs means we verify quote freshness
	// and AK liveness without asserting specific PCR values — PCR state
	// attestation is a Phase 3+ posture probe concern (hexxlock-access
	// posture-agent), not the enrollment handshake.
	if err := akPublic.Verify(quote, nil, req.NonceClient); err != nil {
		return VerifyResponse{}, fmt.Errorf(
			"%w: tpm2-linux: AK quote verification failed (tampered quote or nonce mismatch): %v",
			ErrVerification, err,
		)
	}

	// Delegate EK chain verification to the embedded chainVerifier.
	// This validates EKCertPEM against the pinned vendor root pool,
	// asserts KeyEncipherment | DataEncipherment per TCG EK Credential
	// Profile v2.5 §3.2.7, and returns TIER_CORP on success.
	chainResp, err := v.chain.Verify(ctx, req)
	if err != nil {
		return VerifyResponse{}, fmt.Errorf(
			"%w: tpm2-linux: EK chain verification failed: %v",
			ErrVerification, err,
		)
	}

	// Merge reasons: quote verification + chain verifier reasons.
	reasons := make([]string, 0, 1+len(chainResp.Reasons))
	reasons = append(reasons, "tpm2_linux_quote_verified")
	reasons = append(reasons, chainResp.Reasons...)

	return VerifyResponse{
		Path:    "A_chain",
		Tier:    "TIER_CORP",
		Reasons: reasons,
	}, nil
}
